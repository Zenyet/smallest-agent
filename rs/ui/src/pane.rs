// ============================================================================
// pane.rs —— 内容区显示什么
// ----------------------------------------------------------------------------
// 原来这是个二元开关：`Option<SettingsForm>`，Some 显示设置、None 显示对话。
// 加了「工具」「技能」「Agent」「自动化」四个独立页面之后那个形状不够用了 ——
// 它们不是设置的子页，而是和对话并列的**目的地**。
//
// ## 为什么不把它们做成设置的分区（原来就是那样）
//
// 侧边栏那两行以前是「打开设置并跳到某一页」的快捷方式。用户的原话是
// 「应该是单独渲染的而不是一个打开设置的链接」，而这个区分是实的：
//
//   • 设置是「配一次就不动」的东西（API key、上下文长度）
//   • 工具 / 技能 / Agent / 自动化是**干活过程中**要看和调的东西
//
// 打开设置会把侧边栏整个换成设置导航（那是 waku 的做法，也是对的 ——
// 224px 放不下两组导航）。所以「看一眼有哪些技能」的代价是丢掉会话列表，
// 而那不成比例。
//
// 现在这四个页面**保留会话列表**，只换内容区。设置仍然是整体切换。
// ============================================================================

/// 内容区当前显示哪个页面。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Pane {
    /// 对话（默认）
    #[default]
    Chat,
    /// 设置。表单状态在 ChatView 的 settings 字段上 ——
    /// 这个枚举只说「显示哪个」，不带状态。
    Settings,
    Tools,
    Skills,
    Agents,
    Automations,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_is_chat() {
        // 启动时该看到对话，而不是某个管理页面
        assert_eq!(Pane::default(), Pane::Chat);
    }
}
