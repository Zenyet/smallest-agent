// ============================================================================
// rag/similarity.ts —— 余弦相似度（向量检索的数学核心）
// ----------------------------------------------------------------------------
// 向量检索的本质是「在高维空间里量两个方向有多接近」。
// 余弦相似度 = 两向量夹角的余弦值，关心的是方向，不在乎向量长度。
// 这一点比欧氏距离更适合嵌入向量：同一句话放大 2 倍，语义没变，
// 余弦相似度不变，欧氏距离却翻倍——所以 embedding 检索几乎总选余弦。
// ============================================================================

// 计算两个等长向量的余弦相似度，返回值域 [-1, 1]（嵌入向量通常落在 [0, 1]）。
export function cosineSimilarity(a: number[], b: number[]): number {
  // 长度不等说明调用方用了不同的嵌入模型或代码有 bug，直接报错比返回错误值更安全。
  if (a.length !== b.length) {
    throw new Error(`vector length mismatch: ${a.length} vs ${b.length}`)
  }
  let dot = 0   // 点积 = Σ(aᵢ × bᵢ)
  let normA = 0 // ‖a‖² = Σ(aᵢ²)
  let normB = 0 // ‖b‖² = Σ(bᵢ²)
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i]
    normA += a[i] * a[i]
    normB += b[i] * b[i]
  }
  // 零向量没有方向，余弦无意义；返回 0（「完全不相关」）而非抛错，
  // 让检索过程能继续运行，零向量片段自然排到最末。
  if (normA === 0 || normB === 0) return 0
  // 公式：cos θ = (a · b) / (‖a‖ × ‖b‖)
  return dot / (Math.sqrt(normA) * Math.sqrt(normB))
}
